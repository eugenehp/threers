/// Scan + neighbors for a TX type (`vp9_scan_orders[TX_4X4]`).
pub fn scan_order_4x4(tx_type: TxType) -> (&'static [usize; 16], &'static [u8; 34]) {
    match tx_type {
        TxType::AdstDct => (&SCAN_4X4_ROW, &NEIGHBORS_4X4_ROW),
        TxType::DctAdst => (&SCAN_4X4_COL, &NEIGHBORS_4X4_COL),
        TxType::DctDct | TxType::AdstAdst => (&SCAN_4X4, &NEIGHBORS_4X4),
    }
}

