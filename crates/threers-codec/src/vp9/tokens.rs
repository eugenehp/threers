fn write_token_gt1(e: &mut BoolEncoder, pivot: u8, abs_v: i32) -> u8 {
    let p = &PARETO8_FULL[pivot as usize - 1];
    if abs_v >= CAT1_MIN_VAL {
        e.put_bool(p[0], true);
        if abs_v >= CAT3_MIN_VAL {
            e.put_bool(p[3], true);
            let energy = 5u8;
            if abs_v >= CAT5_MIN_VAL {
                e.put_bool(p[5], true);
                if abs_v >= CAT6_MIN_VAL {
                    e.put_bool(p[7], true);
                    write_extra(e, &CAT6_PROB, (abs_v - CAT6_MIN_VAL) as u32, 14);
                } else {
                    e.put_bool(p[7], false);
                    write_extra(e, &CAT5_PROB, (abs_v - CAT5_MIN_VAL) as u32, 5);
                }
            } else if abs_v >= CAT4_MIN_VAL {
                e.put_bool(p[5], false);
                e.put_bool(p[6], true);
                write_extra(e, &CAT4_PROB, (abs_v - CAT4_MIN_VAL) as u32, 4);
            } else {
                e.put_bool(p[5], false);
                e.put_bool(p[6], false);
                write_extra(e, &CAT3_PROB, (abs_v - CAT3_MIN_VAL) as u32, 3);
            }
            energy
        } else {
            e.put_bool(p[3], false);
            let energy = 4u8;
            if abs_v >= CAT2_MIN_VAL {
                e.put_bool(p[4], true);
                write_extra(e, &CAT2_PROB, (abs_v - CAT2_MIN_VAL) as u32, 2);
            } else {
                e.put_bool(p[4], false);
                write_extra(e, &CAT1_PROB, (abs_v - CAT1_MIN_VAL) as u32, 1);
            }
            energy
        }
    } else {
        e.put_bool(p[0], false);
        if abs_v >= 3 {
            e.put_bool(p[1], true);
            e.put_bool(p[2], abs_v == 4);
            3
        } else {
            // abs_v == 2
            e.put_bool(p[1], false);
            2
        }
    }
}

/// Encode quantized 4×4 coefficients (raster order) into `e`.
///
/// Inverse of libvpx `decode_coefs` for TX_4X4 + the scan order for `tx_type`.
/// `tx_ctx` is the initial band-0 coefficient context (`0..2`). `dc_q` / `ac_q`
/// are kept for API symmetry with the decode path; token bits depend only on
/// `qcoeff` magnitudes.
///
/// Returns the end-of-block index: 0 if all zeros, else one past the last
/// nonzero coefficient in scan order.
pub fn write_coefs(
    e: &mut BoolEncoder,
    qcoeff: &[i32; 16],
    plane_y: bool,
    is_inter: bool,
    tx_ctx: usize,
    tx_type: TxType,
    dc_q: i32,
    ac_q: i32,
) -> usize {
    let _ = (dc_q, ac_q);
    let plane = if plane_y { 0 } else { 1 };
    let probs = if is_inter {
        &COEF_PROBS_4X4_INTER[plane]
    } else {
        &COEF_PROBS_4X4_INTRA[plane]
    };
    let (scan, neighbors) = scan_order_4x4(tx_type);

    let mut eob = 0usize;
    for (i, &rc) in scan.iter().enumerate() {
        if qcoeff[rc] != 0 {
            eob = i + 1;
        }
    }

    let mut c = 0usize;
    let mut ctx = tx_ctx;
    let mut token_cache = [0u8; 16];

    while c < 16 {
        let band = coef_band_4x4(c);
        let prob = &probs[band][ctx];

        if c >= eob {
            e.put_bool(prob[EOB_CONTEXT_NODE], false);
            break;
        }
        e.put_bool(prob[EOB_CONTEXT_NODE], true);

        // Zero run (ZERO bit = 0), then a nonzero (ZERO bit = 1).
        loop {
            let band = coef_band_4x4(c);
            let prob = &probs[band][ctx];
            let v = qcoeff[scan[c]];
            if v == 0 {
                e.put_bool(prob[ZERO_CONTEXT_NODE], false);
                token_cache[scan[c]] = 0;
                c += 1;
                debug_assert!(c < 16);
                ctx = get_coef_context(neighbors, &token_cache, c);
                continue;
            }
            e.put_bool(prob[ZERO_CONTEXT_NODE], true);

            let abs_v = v.unsigned_abs() as i32;
            let energy = if abs_v == 1 {
                e.put_bool(prob[ONE_CONTEXT_NODE], false);
                1u8
            } else {
                e.put_bool(prob[ONE_CONTEXT_NODE], true);
                write_token_gt1(e, prob[PIVOT_NODE], abs_v)
            };
            e.put_bit(v < 0);
            token_cache[scan[c]] = energy;
            c += 1;
            if c < 16 {
                ctx = get_coef_context(neighbors, &token_cache, c);
            }
            break;
        }
    }

    eob
}

