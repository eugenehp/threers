    #[test]
    fn write_read_roundtrip_sparse() {
        let cases: [[i32; 16]; 4] = [
            {
                let mut a = [0i32; 16];
                a[0] = 3;
                a
            },
            {
                let mut a = [0i32; 16];
                a[0] = -1;
                a[5] = 2;
                a
            },
            {
                let mut a = [0i32; 16];
                a[SCAN_4X4[0]] = 1;
                a[SCAN_4X4[3]] = 4;
                a[SCAN_4X4[7]] = -6;
                a
            },
            {
                let mut a = [0i32; 16];
                for i in 0..16 {
                    a[i] = if i % 3 == 0 { (i as i32 % 5) - 2 } else { 0 };
                }
                a
            },
        ];
        for &tx in &[TxType::DctDct, TxType::AdstDct, TxType::DctAdst] {
            for qcoeff in &cases {
                let dc_q = 16;
                let ac_q = 20;
                let mut e = BoolEncoder::new();
                let eob = write_coefs(&mut e, qcoeff, true, false, 1, tx, dc_q, ac_q);
                let bytes = e.finish();
                let mut d = BoolDecoder::new(&bytes);
                let (dq, c) = read_coefs(&mut d, true, 1, tx, dc_q, ac_q);
                assert_eq!(c, eob, "eob mismatch for {:?} tx={tx:?}", qcoeff);
                for i in 0..16 {
                    let q = qcoeff[i];
                    let quant = if i == 0 { dc_q } else { ac_q };
                    assert_eq!(dq[i], q * quant, "pos {i} q={q} dq={}", dq[i]);
                }
            }
        }
    }

