/// Derive `(pStateIdx, valMPS)` from an `(m, n)` pair at `slice_qp` (§9.3.1.1).
pub fn init_state(m: i8, n: i8, slice_qp: i32) -> (u8, u8) {
    let qp = slice_qp.clamp(0, 51);
    let pre = (((m as i32 * qp) >> 4) + n as i32).clamp(1, 126);
    if pre <= 63 {
        ((63 - pre) as u8, 0)
    } else {
        ((pre - 64) as u8, 1)
    }
}
